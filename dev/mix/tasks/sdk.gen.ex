defmodule Mix.Tasks.Sdk.Gen do
  @shortdoc "Regenerates the SDK from openapi.json, deleting stale modules"
  @moduledoc """
  Regenerates the operation and schema modules from `openapi.json`.

  Generated files that the generator did not write in this run belong to
  schemas or operations Polar has removed, so they are deleted: `lib/` always
  mirrors the spec instead of growing forever. Only the generator's own
  `operation_subdirectory` and `schema_subdirectory` are touched, and only
  after generation succeeds.

  Also writes `Polarex.APIVersion`, which pins the `Polar-Version` request
  header to the spec's `info.version`.
  """
  use Mix.Task

  @requirements ["app.start"]

  @profile "default"
  @spec_path "openapi.json"
  @api_version_path "lib/polarex/api_version.ex"

  @impl Mix.Task
  def run(_args) do
    version = @spec_path |> File.read!() |> JSON.decode!() |> get_in(["info", "version"])
    generated_dirs = generated_dirs!()

    %OpenAPI.State{files: files} = OpenAPI.run(@profile, [@spec_path])
    written = MapSet.new(files, &Path.expand(&1.location))

    if MapSet.size(written) == 0 do
      Mix.raise("The generator wrote no files; refusing to delete anything")
    end

    stale =
      for dir <- generated_dirs,
          path <- Path.wildcard(Path.join(dir, "**/*.ex")),
          not MapSet.member?(written, Path.expand(path)),
          do: path

    Enum.each(stale, &File.rm!/1)
    write_api_version!(version)

    Mix.shell().info(
      "Generated #{MapSet.size(written)} modules for Polar API #{version}, " <>
        "deleted #{length(stale)} stale"
    )
  end

  # Without both subdirectories, generated and hand-written modules (such as
  # lib/polarex/support) would share a directory and the cleanup could delete
  # the latter.
  defp generated_dirs! do
    output = Application.fetch_env!(:oapi_generator, String.to_atom(@profile))[:output]
    location = Keyword.fetch!(output, :location)

    for key <- [:operation_subdirectory, :schema_subdirectory] do
      case output[key] do
        subdir when is_binary(subdir) and subdir not in ["", "/"] ->
          Path.join(location, subdir)

        _ ->
          Mix.raise("sdk.gen needs :#{key} set in the :oapi_generator output config")
      end
    end
  end

  defp write_api_version!(version) do
    File.write!(@api_version_path, """
    # Generated by `mix sdk.gen` from openapi.json. Do not edit by hand.
    defmodule Polarex.APIVersion do
      @moduledoc \"""
      The Polar API version this release of Polarex was generated from.

      Every request sends it as the `Polar-Version` header, so Polar answers with
      the same contract the bundled structs describe.
      \"""

      @doc "Returns the pinned Polar API version (`YYYY-MM`)."
      @spec version() :: String.t()
      def version, do: #{inspect(version)}
    end
    """)
  end
end
